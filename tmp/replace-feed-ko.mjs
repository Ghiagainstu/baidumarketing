html = html.replace(/<meta name="description" content="[^"]*"/, '<meta name="description" content="??? ?? ??? ?? ??, ??? ??, ?? ???? ???, ??? ??? ??? ??? ???? ??? ?????."');
html = html.replace(/"headline":\s*"[^"]*"/, '"headline": "??? ?? ?? ?? ???: ?? ??? ??? ??"');

