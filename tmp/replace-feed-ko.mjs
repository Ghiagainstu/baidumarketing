import fs from 'fs';

const htmlPath = 'ko/blog/baidu-feed-ads-explained.html';
const bodyPath = 'C:\\Users\\HYE\\WorkBuddy\\20260411211839\\tmp\\feed-ads-ko-body.html';

let html = fs.readFileSync(htmlPath, 'utf8');
