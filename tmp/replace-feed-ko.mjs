// Find article-content
const startIdx = html.indexOf('<article class="article-content">');
const endMarker = '</article>';
const endIdx = html.indexOf(endMarker, startIdx);

if (startIdx === -1 || endIdx === -1) { console.error('Not found'); process.exit(1); }

html = html.substring(0, startIdx) + 
       '<article class="article-content">\n' + newBody + '\n      </article>' + 
       html.substring(endIdx + endMarker.length);

// Update title
html = html.replace(/<title>[^<]*<\/title>/, '<title>??? ?? ?? ?? ???: ?? ??? ??? ?? ¡ª Baidu PPC Pro Blog</title>');
